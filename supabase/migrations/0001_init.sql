-- Vinayak procurement agent schema. Isolated in the `vinayak` schema inside the
-- shared ticketing_system project. Does not touch public / future_scheduling.
create schema if not exists vinayak;
create extension if not exists vector with schema extensions;
create extension if not exists pg_trgm;

set local search_path to vinayak, extensions, public;

-- Raw ERP item codes. NO unique on item_code: the real export repeats codes,
-- and surfacing those duplicates is part of the matching step. `id` is the PK.
create table vinayak.item_codes (
  id bigint generated by default as identity primary key,
  item_code text not null,
  description text not null,
  embedding extensions.vector(1536),   -- nullable; reserved for optional embedding upgrade
  created_at timestamptz not null default now()
);
create index item_codes_desc_trgm_idx on vinayak.item_codes using gin (description gin_trgm_ops);
create index item_codes_code_trgm_idx on vinayak.item_codes using gin (item_code gin_trgm_ops);

create table vinayak.requirements (
  id uuid primary key default gen_random_uuid(),
  source text not null check (source in ('form', 'whatsapp', 'voice')),
  project text not null,
  raw_text text not null,
  created_at timestamptz not null default now()
);

create table vinayak.requirement_lines (
  id uuid primary key default gen_random_uuid(),
  requirement_id uuid not null references vinayak.requirements(id) on delete cascade,
  description text not null,
  uom text not null,
  qty numeric,
  wo_code text,
  matched_item_code text,            -- plain text: existing OR newly suggested code
  created_at timestamptz not null default now()
);

create table vinayak.vendors (
  name text primary key,
  category text not null,
  contact text,
  on_time_pct numeric not null default 0 check (on_time_pct between 0 and 100),
  rate_variance_pct numeric not null default 0,
  rework_count integer not null default 0 check (rework_count >= 0),
  quality_1_5 numeric not null default 1 check (quality_1_5 between 1 and 5),
  created_at timestamptz not null default now()
);

create table vinayak.quotes (
  id bigint generated by default as identity primary key,
  requirement_id uuid references vinayak.requirements(id) on delete set null,
  vendor text not null references vinayak.vendors(name) on update cascade,
  source_file text not null,
  item_label text not null,
  matched_item_code text,
  uom_original text not null,
  qty_original numeric,
  rate_original numeric,
  uom_norm text not null default 'SQM' check (uom_norm = 'SQM'),
  qty_norm numeric,
  unit_rate_norm numeric,
  gst_pct numeric,
  freight numeric,
  payment_terms text,
  delivery_days integer check (delivery_days is null or delivery_days >= 0),
  confidence numeric not null check (confidence between 0 and 1),
  flags text[] not null default '{}',
  created_at timestamptz not null default now()
);

create table vinayak.comparative_statements (
  id bigint generated by default as identity primary key,
  requirement_id uuid not null references vinayak.requirements(id) on delete cascade,
  statement jsonb not null,
  created_at timestamptz not null default now()
);

create table vinayak.recommendations (
  id bigint generated by default as identity primary key,
  requirement_id uuid not null references vinayak.requirements(id) on delete cascade,
  recommendation jsonb not null,
  created_at timestamptz not null default now()
);

create index requirement_lines_requirement_id_idx on vinayak.requirement_lines(requirement_id);
create index quotes_requirement_id_idx on vinayak.quotes(requirement_id);
create index comparative_statements_requirement_id_idx on vinayak.comparative_statements(requirement_id);
create index recommendations_requirement_id_idx on vinayak.recommendations(requirement_id);

-- RLS on, no policies: anon/browser client sees nothing. All data access is via
-- the Next.js API routes using the service-role server client (bypasses RLS).
alter table vinayak.item_codes enable row level security;
alter table vinayak.requirements enable row level security;
alter table vinayak.requirement_lines enable row level security;
alter table vinayak.vendors enable row level security;
alter table vinayak.quotes enable row level security;
alter table vinayak.comparative_statements enable row level security;
alter table vinayak.recommendations enable row level security;

grant usage on schema vinayak to anon, authenticated, service_role;
grant all on all tables in schema vinayak to service_role;
grant all on all sequences in schema vinayak to service_role;
alter default privileges in schema vinayak grant all on tables to service_role;
alter default privileges in schema vinayak grant all on sequences to service_role;
