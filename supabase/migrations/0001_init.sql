create schema if not exists extensions;
create schema if not exists vinayak;

create extension if not exists vector with schema extensions;

create table vinayak.item_codes (
  id bigint generated by default as identity primary key,
  item_code text not null unique,
  description text not null,
  embedding extensions.vector(1536),
  created_at timestamptz not null default now()
);

create table vinayak.requirements (
  id uuid primary key default gen_random_uuid(),
  source text not null check (source in ('form', 'whatsapp', 'voice')),
  project text not null,
  raw_text text not null,
  created_at timestamptz not null default now()
);

create table vinayak.requirement_lines (
  id uuid primary key default gen_random_uuid(),
  requirement_id uuid not null
    references vinayak.requirements(id) on delete cascade,
  description text not null,
  uom text not null,
  qty numeric,
  wo_code text,
  matched_item_code text
    references vinayak.item_codes(item_code) on update cascade,
  created_at timestamptz not null default now()
);

create table vinayak.vendors (
  name text primary key,
  category text not null,
  contact text,
  on_time_pct numeric not null default 0
    check (on_time_pct between 0 and 100),
  rate_variance_pct numeric not null default 0,
  rework_count integer not null default 0 check (rework_count >= 0),
  quality_1_5 numeric not null default 1
    check (quality_1_5 between 1 and 5),
  created_at timestamptz not null default now()
);

create table vinayak.quotes (
  id bigint generated by default as identity primary key,
  requirement_id uuid
    references vinayak.requirements(id) on delete set null,
  vendor text not null references vinayak.vendors(name) on update cascade,
  source_file text not null,
  item_label text not null,
  matched_item_code text
    references vinayak.item_codes(item_code) on update cascade,
  uom_original text not null,
  qty_original numeric,
  rate_original numeric,
  uom_norm text not null default 'SQM' check (uom_norm = 'SQM'),
  qty_norm numeric,
  unit_rate_norm numeric,
  gst_pct numeric,
  freight numeric,
  payment_terms text,
  delivery_days integer check (delivery_days is null or delivery_days >= 0),
  confidence numeric not null check (confidence between 0 and 1),
  flags text[] not null default '{}',
  created_at timestamptz not null default now()
);

create table vinayak.comparative_statements (
  id bigint generated by default as identity primary key,
  requirement_id uuid not null
    references vinayak.requirements(id) on delete cascade,
  statement jsonb not null,
  created_at timestamptz not null default now()
);

create table vinayak.recommendations (
  id bigint generated by default as identity primary key,
  requirement_id uuid not null
    references vinayak.requirements(id) on delete cascade,
  recommendation jsonb not null,
  created_at timestamptz not null default now()
);

create index requirement_lines_requirement_id_idx
  on vinayak.requirement_lines(requirement_id);
create index quotes_requirement_id_idx
  on vinayak.quotes(requirement_id);
create index comparative_statements_requirement_id_idx
  on vinayak.comparative_statements(requirement_id);
create index recommendations_requirement_id_idx
  on vinayak.recommendations(requirement_id);

